export const dictionaries = { en, th } as const;

export type Dictionary = typeof en;

/** Dot-path into the dictionary, e.g. `"dashboard.freedomTitle"`. */
export type TranslationKey = Paths<Dictionary>;

type Paths<T> = T extends object
  ? {
      [K in keyof T & string]: T[K] extends object ? `${K}.${Paths<T[K]>}` : K;
    }[keyof T & string]
  : never;

/** Resolve a dot-path, returning the key itself if it is missing. */
export function lookup(lang: Language, key: string): string {
  const dict: unknown = dictionaries[lang];
  const value = key
    .split(".")
    .reduce<unknown>((acc, part) => (acc as Record<string, unknown>)?.[part], dict);
  return typeof value === "string" ? value : key;
}

/** `t("goals.remaining", { amount: "฿2,000" })` */
export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    name in vars ? String(vars[name]) : `{${name}}`,
  );
}
